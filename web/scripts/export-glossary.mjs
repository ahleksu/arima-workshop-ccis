// Generate docs/glossary.md from src/glossary.json.
// Usage: node scripts/export-glossary.mjs          (write the file)
//        node scripts/export-glossary.mjs --check  (exit 1 if the file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const jsonPath = resolve(here, '../src/glossary.json');
const outPath = resolve(here, '../../docs/glossary.md');

function fail(message) {
  console.error(`export-glossary: ${message}`);
  process.exit(1);
}

const slug = (term) => term.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

let data;
try {
  data = JSON.parse(readFileSync(jsonPath, 'utf8'));
} catch {
  fail(`cannot read or parse ${jsonPath}`);
}
if (data.schema_version !== 1 || !Array.isArray(data.terms)) {
  fail('the glossary file must have schema_version 1 and a terms array');
}

const terms = [...data.terms].sort((a, b) => a.term.localeCompare(b.term, 'en', { sensitivity: 'base' }));
const names = new Set(terms.map((t) => t.term));
for (const t of terms) {
  for (const s of t.see ?? []) {
    if (!names.has(s)) fail(`"${t.term}" links to "${s}", which is not a term`);
  }
}

const lines = [
  '# Glossary',
  '',
  'Plain definitions of the terms used in the ARIMA workshop. The web explorer shows the same list on its Glossary page.',
  '',
  '<!-- Generated by web/scripts/export-glossary.mjs from web/src/glossary.json. Do not edit this file by hand. -->',
  '',
];
for (const t of terms) {
  lines.push(`## ${t.term}`, '');
  if (t.full) lines.push(`*${t.full}*`, '');
  lines.push(t.definition, '');
  if ((t.see ?? []).length > 0) {
    lines.push(`See also: ${t.see.map((s) => `[${s}](#${slug(s)})`).join(', ')}`, '');
  }
}
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    // A missing file counts as out of date.
  }
  if (current !== output) fail('docs/glossary.md is out of date. Run: npm run export-glossary');
} else {
  writeFileSync(outPath, output);
  console.log(`export-glossary: wrote ${terms.length} terms to docs/glossary.md`);
}
